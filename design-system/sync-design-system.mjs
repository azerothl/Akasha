#!/usr/bin/env node
/**
 * Sync design-system CSS from Akasha monorepo to akasha-ui, code-studio, Akasha_app.
 * Usage: node design-system/sync-design-system.mjs
 */
import { copyFileSync, mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = dirname(fileURLToPath(import.meta.url));
const ROOT = resolve(__dirname, "..");

const FILES = ["tokens.css", "semantic.css", "tooltip.css", "notifications.css"];

const TARGETS = [
  join(ROOT, "apps/akasha-ui/src/design-system"),
  join(ROOT, "../akasha-code-studio/src/design-system"),
];

function ensureDir(path) {
  mkdirSync(path, { recursive: true });
}

function syncToDir(targetDir) {
  ensureDir(targetDir);
  for (const file of FILES) {
    copyFileSync(join(__dirname, file), join(targetDir, file));
    console.log(`  → ${join(targetDir, file)}`);
  }
}

function buildAkashaAppBundle() {
  const outPath = join(ROOT, "../Akasha_app/css/akasha-design-system.css");
  const header = "/* DO NOT EDIT — generated by design-system/sync-design-system.mjs */\n\n";
  const body = FILES.map((f) => readFileSync(join(__dirname, f), "utf8")).join("\n\n");
  ensureDir(dirname(outPath));
  writeFileSync(outPath, header + body, "utf8");
  console.log(`  → ${outPath}`);
}

console.log("Syncing design-system…");
for (const target of TARGETS) {
  syncToDir(target);
}
buildAkashaAppBundle();
console.log("Done.");
